// Generates supabase/migrations/*_seed_templates.sql from packages/shared/src/templates.ts
// Usage: pnpm gen:templates   (requires tsx via npx)
import { writeFileSync } from "node:fs";
import { TEMPLATE_SPECS, buildTemplateDefinition, STOPWORDS } from "../packages/shared/src/index.ts";
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const header = "-- Generated by scripts/gen-templates-sql.mjs — do not edit by hand.\n\n";
const stop = header + "insert into private.stopwords (word) values " + [...STOPWORDS].map((w) => `(${q(w)})`).join(",") + "\non conflict do nothing;\n";
writeFileSync(new URL("../supabase/migrations/20261118000600_seed_stopwords.sql", import.meta.url), stop);
let sql = header + "-- Optional: copies the built-in template library into public.form_templates (admin-curated catalogue).\n";
TEMPLATE_SPECS.forEach((spec, i) => {
  const def = buildTemplateDefinition(spec);
  const n = def.questions.filter((x) => !["heading", "statement"].includes(x.type)).length;
  sql += `insert into public.form_templates (slug, category, title, summary, definition, question_count, sort_order) values (${q(spec.slug)}, ${q(spec.category)}, ${q(spec.title)}, ${q(spec.summary)}, ${q(JSON.stringify(def))}::jsonb, ${n}, ${i})\non conflict (slug) do update set category = excluded.category, title = excluded.title, summary = excluded.summary, definition = excluded.definition, question_count = excluded.question_count, sort_order = excluded.sort_order;\n`;
});
writeFileSync(new URL("../supabase/seed/templates.sql", import.meta.url), sql);
console.log("templates:", TEMPLATE_SPECS.length);
